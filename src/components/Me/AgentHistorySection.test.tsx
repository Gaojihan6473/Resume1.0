import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { AgentHistorySection } from './AgentHistorySection'
import { deleteAgentHistory, fetchAgentHistory, fetchAgentHistoryDetail, type AgentHistorySummary } from '../../lib/api/jdAnalysisRecords'
import type { JDAnalysisRecord } from '../../types/jdAnalysisHistory'
import { useAuthStore } from '../../store/authStore'

vi.mock('../../lib/api/jdAnalysisRecords', () => ({ deleteAgentHistory: vi.fn(), fetchAgentHistory: vi.fn(), fetchAgentHistoryDetail: vi.fn() }))
const summary: AgentHistorySummary = { id: 'analysis', resume_id: 'resume', title: '小鱼科技 · 产品经理', resume_title_snapshot: '产品简历', company_snapshot: '小鱼科技', position_snapshot: '产品经理', status: 'success', analyzed_at: '2026-10-29T01:00:00Z', created_at: '2026-10-29T01:00:00Z' }

describe('Agent history section', () => {
  beforeEach(() => {
    vi.resetAllMocks()
    useAuthStore.setState({ user: { id: 'owner', email: '', keyName: '' } })
    vi.mocked(fetchAgentHistory).mockResolvedValue({ records: [summary], total: 1 })
    vi.mocked(fetchAgentHistoryDetail).mockResolvedValue({ ...summary, jd_text_snapshot: '负责产品规划', analysis_result: { kind: 'resume-agent', schemaVersion: 1, completionStatus: 'no_changes', proposal: null, plan: { goalSummary: '当前简历已覆盖核心要求' } } } as JDAnalysisRecord)
  })
  afterEach(cleanup)
  it('opens deletion without expanding the row, supports cancellation, and refreshes after confirmation', async () => {
    vi.mocked(deleteAgentHistory).mockResolvedValue(undefined)
    render(<AgentHistorySection onOpenResume={vi.fn()} />)
    const remove = await screen.findByRole('button', { name: `删除分析历史 ${summary.title}` })
    fireEvent.click(remove)
    expect(fetchAgentHistoryDetail).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: '取消' }))
    expect(deleteAgentHistory).not.toHaveBeenCalled()
    fireEvent.click(remove)
    vi.mocked(fetchAgentHistory).mockResolvedValue({ records: [], total: 0 })
    fireEvent.click(screen.getByRole('button', { name: '确认删除' }))
    await screen.findByText('暂无 Agent 分析记录')
    expect(deleteAgentHistory).toHaveBeenCalledExactlyOnceWith('analysis', 'owner')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(fetchAgentHistory).toHaveBeenLastCalledWith('', 0)
  })
  it('keeps the history on delete failure and allows retrying', async () => {
    vi.mocked(deleteAgentHistory).mockRejectedValueOnce(new Error('删除失败，请重试')).mockResolvedValueOnce(undefined)
    render(<AgentHistorySection onOpenResume={vi.fn()} />)
    fireEvent.click(await screen.findByRole('button', { name: `删除分析历史 ${summary.title}` }))
    fireEvent.click(screen.getByRole('button', { name: '确认删除' }))
    expect(await within(screen.getByRole('dialog')).findByRole('alert')).toHaveTextContent('删除失败，请重试')
    expect(screen.getAllByRole('listitem')).toHaveLength(1)
    fireEvent.click(screen.getByRole('button', { name: '确认删除' }))
    await waitFor(() => expect(deleteAgentHistory).toHaveBeenCalledTimes(2))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
  })
  it('loads lightweight summaries and fetches the selected detail only on expansion', async () => {
    const open = vi.fn()
    render(<AgentHistorySection onOpenResume={open} />)
    const row = await screen.findByRole('button', { name: /小鱼科技 · 产品经理/, expanded: false })
    expect(row.textContent?.match(/产品经理/g)).toHaveLength(1)
    expect(within(row).getByText('产品简历')).toBeInTheDocument()
    expect(fetchAgentHistoryDetail).not.toHaveBeenCalled()
    fireEvent.click(row)
    expect(await screen.findByText('无需修改')).toBeInTheDocument()
    expect(screen.getByText('当前简历已覆盖核心要求')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '打开关联简历' }))
    expect(open).toHaveBeenCalledWith('resume')
    expect(fetchAgentHistoryDetail).toHaveBeenCalledWith('analysis')
  })
  it('groups the saved proposal into matching and readable before/after suggestions', async () => {
    vi.mocked(fetchAgentHistoryDetail).mockResolvedValue({ ...summary, analysis_result: { kind: 'resume-agent', schemaVersion: 1, completionStatus: 'partial', proposal: { goalSummary: '突出需求分析经验', targetRequirements: [{ id: 'r1', requirement: '具备需求分析能力', coverage: 'covered' }], patches: [0, 1].map((index) => ({ key: `p${index}`, itemTitle: `项目经历 ${index + 1}`, kind: 'rich_text_replace', risk: 'low', reason: '突出已有成果', originalText: '参与需求分析', revisedText: '负责需求梳理与分析' })), missingEvidence: [{ message: '补充业务指标' }], validation: { warnings: [] } } } } as unknown as JDAnalysisRecord)
    render(<AgentHistorySection onOpenResume={vi.fn()} />)
    fireEvent.click(await screen.findByRole('button', { name: /小鱼科技 · 产品经理/, expanded: false }))
    expect(await screen.findByText('部分完成')).toBeInTheDocument()
    expect(screen.getByRole('region', { name: '岗位匹配' })).toHaveTextContent('已覆盖 1 / 1 项')
    const suggestions = screen.getByRole('region', { name: '优化建议' })
    const cards = suggestions.querySelectorAll('details')
    expect(cards[0]).toHaveAttribute('open')
    expect(cards[1]).not.toHaveAttribute('open')
    expect(cards[0]).toHaveTextContent('参与需求分析')
    expect(cards[0]).toHaveTextContent('负责需求梳理与分析')
    expect(screen.queryByRole('complementary', { name: '补充与提醒' })).not.toBeInTheDocument()
    expect(screen.queryByText('补充业务指标')).not.toBeInTheDocument()
    expect(screen.queryByText('待补充证据')).not.toBeInTheDocument()
  })
  it('shows five, appends five without replacing rows, and resets search including Chinese composition', async () => {
    vi.mocked(fetchAgentHistory).mockImplementation(async (_query, page = 0) => ({ records: Array.from({ length: 5 }, (_, i) => ({ ...summary, id: `record-${page * 5 + i}` })), total: 11 }))
    render(<AgentHistorySection onOpenResume={vi.fn()} />)
    await screen.findByText('已展示 5 / 共 11 条')
    expect(screen.getAllByRole('listitem')).toHaveLength(5)
    fireEvent.click(screen.getByRole('button', { name: '加载更多分析记录' }))
    await waitFor(() => expect(fetchAgentHistory).toHaveBeenLastCalledWith('', 1))
    await screen.findByText('已展示 10 / 共 11 条')
    expect(screen.getAllByRole('listitem')).toHaveLength(10)
    const input = screen.getByRole('textbox', { name: '搜索分析历史' })
    fireEvent.compositionStart(input)
    fireEvent.change(input, { target: { value: '产品' }, isComposing: true })
    fireEvent.compositionEnd(input, { target: { value: '产品' } })
    await waitFor(() => expect(fetchAgentHistory).toHaveBeenLastCalledWith('产品', 0))
    await screen.findByText('已展示 5 / 共 11 条')
  })
  it('keeps loaded rows on a failed load-more and retries the same page', async () => {
    vi.mocked(fetchAgentHistory).mockResolvedValueOnce({ records: [summary], total: 6 }).mockRejectedValueOnce(new Error('追加失败')).mockResolvedValueOnce({ records: [{ ...summary, id: 'next' }], total: 6 })
    render(<AgentHistorySection onOpenResume={vi.fn()} />)
    await screen.findByText('已展示 1 / 共 6 条')
    fireEvent.click(screen.getByRole('button', { name: '加载更多分析记录' }))
    await screen.findByText('追加失败')
    expect(screen.getAllByRole('listitem')).toHaveLength(1)
    fireEvent.click(screen.getByRole('button', { name: '重试分析历史' }))
    await screen.findByText('已展示 2 / 共 6 条')
    expect(fetchAgentHistory).toHaveBeenLastCalledWith('', 1)
  })
  it('reports failed loading, retries, and distinguishes no history from no search matches', async () => {
    vi.mocked(fetchAgentHistory).mockRejectedValueOnce(new Error('历史暂时不可用')).mockResolvedValue({ records: [], total: 0 })
    render(<AgentHistorySection onOpenResume={vi.fn()} />)
    expect(await screen.findByRole('alert')).toHaveTextContent('历史暂时不可用')
    fireEvent.click(screen.getByRole('button', { name: '重试分析历史' }))
    expect(await screen.findByText('暂无 Agent 分析记录')).toBeInTheDocument()
    fireEvent.change(screen.getByRole('textbox', { name: '搜索分析历史' }), { target: { value: '不存在' } })
    expect(await screen.findByText('没有符合条件的分析记录')).toBeInTheDocument()
  })
  it('ignores a previous account response after its section unmounts', async () => {
    let resolve!: (value: { records: AgentHistorySummary[]; total: number }) => void
    vi.mocked(fetchAgentHistory).mockReturnValueOnce(new Promise((done) => { resolve = done }))
    const view = render(<AgentHistorySection key="old-user" onOpenResume={vi.fn()} />)
    await waitFor(() => expect(fetchAgentHistory).toHaveBeenCalledOnce())
    vi.mocked(fetchAgentHistory).mockResolvedValue({ records: [], total: 0 })
    view.rerender(<AgentHistorySection key="new-user" onOpenResume={vi.fn()} />)
    await screen.findByText('暂无 Agent 分析记录')
    resolve({ records: [summary], total: 1 })
    await waitFor(() => expect(screen.queryByText(summary.title)).not.toBeInTheDocument())
  })
})
